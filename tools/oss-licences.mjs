// The list of spec open-source-licences (bipe-shared product/screens/open-source-licences.json), made from
// tools/licences.json, the dependency list that the licence check reads. Never typed by hand.
// Usage: node tools/oss-licences.mjs   (writes the two files below)
// The tool-tests job fails when the written files differ from what this makes (tools/oss-licences.test.mjs).
//
// - ios/Bipe/Resources/OpenSourceLicences.json
// - android/app/src/main/assets/open_source_licences.json
//
// Bipe comes first (AGPL-3.0-only with the app store permission, ADR 0144), then the dependencies of the platform by
// name. A vendored package uses its own LICENSE file; every other package the standard text of its SPDX id from
// tools/licence-texts/<id>.txt.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { REPO_ROOT, isMain } from './lib.mjs';

export const OUTPUTS = {
  ios: 'ios/Bipe/Resources/OpenSourceLicences.json',
  android: 'android/app/src/main/assets/open_source_licences.json',
};

const ECOSYSTEMS = { ios: ['swiftpm', 'vendored'], android: ['gradle', 'vendored'] };

// The LICENSE file of each vendored package, per platform.
const VENDORED_LICENCE = {
  '@phosphor-icons/core': { ios: 'ios/Phosphor/LICENSE', android: 'android/libraries/phosphor/LICENSE' },
};

const read = (root, path) => readFileSync(join(root, path), 'utf8').replace(/\r\n/g, '\n').trimEnd();

export function licenceList(platform, root = REPO_ROOT) {
  const { packages } = JSON.parse(readFileSync(join(root, 'tools/licences.json'), 'utf8'));
  const texts = {};
  const textOf = (id) => {
    texts[id] ??= read(root, `tools/licence-texts/${id}.txt`);
    return id;
  };
  const dependencies = Object.entries(packages)
    .filter(([, p]) => ECOSYSTEMS[platform].includes(p.ecosystem))
    .sort(([a], [b]) => a.toLowerCase().localeCompare(b.toLowerCase()))
    .map(([name, p]) => {
      const vendored = VENDORED_LICENCE[name]?.[platform];
      if (p.ecosystem === 'vendored' && !vendored) throw new Error(`oss-licences: no LICENSE path for vendored ${name}`);
      return vendored ? { name, licence: p.licence, text: read(root, vendored) } : { name, licence: textOf(p.licence) };
    });
  const bipe = {
    name: 'Bipe',
    licence: 'AGPL-3.0-only',
    text: `${read(root, 'LICENSE')}\n\n${read(root, 'APP-STORE-PERMISSION.md')}`,
  };
  return {
    $comment: 'Generated by bipe-app tools/oss-licences.mjs from tools/licences.json. Do not edit.',
    components: [bipe, ...dependencies],
    texts,
  };
}

export const render = (platform, root = REPO_ROOT) => `${JSON.stringify(licenceList(platform, root), null, 2)}\n`;

if (isMain(import.meta.url)) {
  for (const [platform, path] of Object.entries(OUTPUTS)) {
    mkdirSync(dirname(join(REPO_ROOT, path)), { recursive: true });
    writeFileSync(join(REPO_ROOT, path), render(platform));
    console.log(`oss-licences: wrote ${path}`);
  }
}
