// Phosphor icons (MIT, ADR 0145) for both apps, from the @phosphor-icons/core npm package.
// tools/phosphor.json names the version, the weight and the icons the apps use.
// Usage: node tools/phosphor.mjs <folder of an unpacked @phosphor-icons/core package>
//   (npm pack @phosphor-icons/core@<version> && tar -xzf phosphor-icons-core-<version>.tgz: the folder is "package")
//
// Writes, and replaces what was there:
// - ios/Phosphor: Swift package with Resources/Phosphor.xcassets (one template SVG per icon) and PhosphorIcon.swift
// - android/libraries/phosphor: module with res/drawable/phosphor_<name>.xml (vector drawables) and PhosphorIcon.kt
// - LICENSE (Phosphor's MIT licence) in both folders

import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { REPO_ROOT, isMain } from './lib.mjs';

const HEADER = [
  '// SPDX-License-Identifier: AGPL-3.0-only',
  '// Additional permission: APP-STORE-PERMISSION.md (AGPL section 7)',
  '// Copyright 2026 Bipe contributors',
].join('\n');

// A Phosphor glyph: viewBox 0 0 256 256 and one path, filled with currentColor.
export function parseIcon(svg, name) {
  const m = /^<svg [^>]*viewBox="0 0 256 256"[^>]*><path d="([^"]+)"\/><\/svg>\s*$/.exec(svg.trim());
  if (!m) throw new Error(`phosphor: ${name}.svg is not one path in a 256 x 256 viewBox`);
  if (!/^[MmLlHhVvCcSsQqTtAaZz0-9.,\s-]+$/.test(m[1])) throw new Error(`phosphor: ${name}.svg path has unknown commands`);
  return m[1];
}

// iOS: the asset catalog renders the SVG as a template image, so the colour comes from the view.
export function templateSvg(path) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256" viewBox="0 0 256 256"><path fill="#000000" d="${path}"/></svg>\n`;
}

// Android: a vector drawable in a 24 dp box. Compose tints it.
export function vectorDrawable(path) {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Phosphor Icons (MIT), generated by bipe-app tools/phosphor.mjs. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="256"
    android:viewportHeight="256">
    <path
        android:fillColor="#FF000000"
        android:pathData="${path}" />
</vector>
`;
}

export const swiftCase = (name) => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
export const kotlinCase = (name) => name.replace(/-/g, '_').toUpperCase();
export const resourceName = (name) => `phosphor_${name.replace(/-/g, '_')}`;

export function swiftSource(names, version) {
  const cases = names.map((n) => `    case ${swiftCase(n)} = "${n}"`).join('\n');
  return `${HEADER}

// Generated by bipe-app tools/phosphor.mjs from @phosphor-icons/core ${version}. Do not edit.

import SwiftUI

/// Phosphor icons (MIT) that the app uses. Add an icon in tools/phosphor.json, then run tools/phosphor.mjs.
public enum PhosphorIcon: String, CaseIterable, Sendable {
${cases}

    /// The icon as a template image. Set its colour with foregroundStyle.
    /// Decorative: VoiceOver skips it and never reads the file name. A control that shows only an icon
    /// sets its own accessibilityLabel (tools/a11y.mjs, bipe-chat/bipe#495).
    public var image: Image {
        Image(decorative: rawValue, bundle: .module)
    }

    /// The icon as an image that VoiceOver reads with this label, for an icon that says something on its own.
    public func labelledImage(_ label: String) -> Image {
        Image(rawValue, bundle: .module, label: Text(label))
    }

    /// The icon drawn at a fixed size in points, for a toolbar item. A toolbar keeps only the image of a
    /// Label or Button: it drops a frame and stretches a resizable image to the full bar.
    public func toolbarImage(size: CGFloat) -> Image {
        guard let icon = UIImage(named: rawValue, in: .module, with: nil) else { return image }
        let sized = UIGraphicsImageRenderer(size: CGSize(width: size, height: size)).image { _ in
            icon.draw(in: CGRect(x: 0, y: 0, width: size, height: size))
        }
        guard let cgImage = sized.cgImage else { return image }
        return Image(decorative: cgImage, scale: sized.scale).renderingMode(.template)
    }
}
`;
}

export function kotlinSource(names, version) {
  const entries = names.map((n) => `    ${kotlinCase(n)}("${n}", R.drawable.${resourceName(n)}),`).join('\n');
  return `${HEADER}

// Generated by bipe-app tools/phosphor.mjs from @phosphor-icons/core ${version}. Do not edit.

package chat.bipe.phosphor

import androidx.annotation.DrawableRes

/** Phosphor icons (MIT) that the app uses. Add an icon in tools/phosphor.json, then run tools/phosphor.mjs. */
enum class PhosphorIcon(val id: String, @DrawableRes val drawable: Int) {
${entries}
}
`;
}

const json = (value) => JSON.stringify(value, null, 2) + '\n';

export function writeIcons(pkg, root = REPO_ROOT) {
  const config = JSON.parse(readFileSync(join(root, 'tools/phosphor.json'), 'utf8'));
  const meta = JSON.parse(readFileSync(join(pkg, 'package.json'), 'utf8'));
  if (meta.name !== '@phosphor-icons/core' || meta.version !== config.version) {
    throw new Error(`phosphor: ${pkg} is ${meta.name}@${meta.version}, tools/phosphor.json wants @phosphor-icons/core@${config.version}`);
  }
  if (meta.license !== 'MIT') throw new Error(`phosphor: licence is ${meta.license}, not MIT`);
  const names = [...config.icons].sort();
  const paths = Object.fromEntries(
    names.map((n) => [n, parseIcon(readFileSync(join(pkg, 'assets', config.weight, `${n}.svg`), 'utf8'), n)]),
  );

  const ios = join(root, 'ios/Phosphor');
  const catalog = join(ios, 'Sources/Phosphor/Resources/Phosphor.xcassets');
  rmSync(catalog, { recursive: true, force: true });
  mkdirSync(catalog, { recursive: true });
  writeFileSync(join(catalog, 'Contents.json'), json({ info: { author: 'xcode', version: 1 } }));
  for (const n of names) {
    const set = join(catalog, `${n}.imageset`);
    mkdirSync(set);
    writeFileSync(join(set, `${n}.svg`), templateSvg(paths[n]));
    writeFileSync(
      join(set, 'Contents.json'),
      json({
        images: [{ filename: `${n}.svg`, idiom: 'universal' }],
        info: { author: 'xcode', version: 1 },
        properties: { 'preserves-vector-representation': true, 'template-rendering-intent': 'template' },
      }),
    );
  }
  writeFileSync(join(ios, 'Sources/Phosphor/PhosphorIcon.swift'), swiftSource(names, config.version));
  copyFileSync(join(pkg, 'LICENSE'), join(ios, 'LICENSE'));

  const android = join(root, 'android/libraries/phosphor');
  const drawable = join(android, 'src/main/res/drawable');
  rmSync(drawable, { recursive: true, force: true });
  mkdirSync(drawable, { recursive: true });
  for (const n of names) writeFileSync(join(drawable, `${resourceName(n)}.xml`), vectorDrawable(paths[n]));
  const kotlinDir = join(android, 'src/main/kotlin/chat/bipe/phosphor');
  mkdirSync(kotlinDir, { recursive: true });
  writeFileSync(join(kotlinDir, 'PhosphorIcon.kt'), kotlinSource(names, config.version));
  copyFileSync(join(pkg, 'LICENSE'), join(android, 'LICENSE'));
  return names;
}

if (isMain(import.meta.url)) {
  const pkg = process.argv[2];
  if (!pkg) {
    console.error('Usage: node tools/phosphor.mjs <folder of an unpacked @phosphor-icons/core package>');
    process.exit(2);
  }
  const names = writeIcons(pkg);
  console.log(`phosphor: wrote ${names.length} icons (${names.join(', ')})`);
}
